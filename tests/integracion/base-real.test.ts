/**
 * Integration tests against the REAL Supabase project, touching only the demo
 * businesses (the test bench). They check what unit tests can't: SQL functions
 * and row-level security.
 *
 *   npm run test:integracion        (needs .env.local with the Supabase keys)
 *
 * Every order created here is cancelled at the end, which returns its stock.
 */
import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import { createClient, type SupabaseClient } from '@supabase/supabase-js';
import fs from 'node:fs';
import path from 'node:path';

const envFile = path.resolve(__dirname, '../../.env.local');
const env: Record<string, string> = fs.existsSync(envFile)
  ? Object.fromEntries(
      fs.readFileSync(envFile, 'utf8').split(/\r?\n/)
        .filter(l => l.includes('=') && !l.trim().startsWith('#'))
        .map(l => { const i = l.indexOf('='); return [l.slice(0, i).trim(), l.slice(i + 1).trim().replace(/^"|"$/g, '')]; }),
    )
  : {};
const URL = env.NEXT_PUBLIC_SUPABASE_URL ?? process.env.NEXT_PUBLIC_SUPABASE_URL;
const ANON = env.NEXT_PUBLIC_SUPABASE_ANON_KEY ?? process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
const SERVICE = env.SUPABASE_SERVICE_ROLE_KEY ?? process.env.SUPABASE_SERVICE_ROLE_KEY;
const ready = !!(URL && ANON && SERVICE);

const DEMO_SLUG = 'hungry-ape-demo';
const PRO_DEMO_SLUG = 'hungry-ape-pro-demo';
const PRO_DEMO_EMAIL = env.DEMO_PRO_EMAIL || 'demo-pro@hungryape.app';

const opts = { auth: { persistSession: false, autoRefreshToken: false } };
let anon: SupabaseClient;
let service: SupabaseClient;
let owner: SupabaseClient; // signed in as the Pro demo owner
let demoTenantId = '';
let proTenantId = '';
const createdOrders: string[] = [];

async function demoProduct(tenantId: string, minStock = 15) {
  const { data: withRequired } = await service.from('product_modifier_groups').select('product_id').eq('tenant_id', tenantId).eq('required', true);
  const blocked = new Set((withRequired ?? []).map(g => g.product_id));
  const { data } = await service.from('products').select('id, name, price, stock')
    .eq('tenant_id', tenantId).eq('is_archived', false).eq('is_available', true).gte('stock', minStock);
  const p = (data ?? []).find(x => !blocked.has(x.id));
  if (!p) throw new Error('La demo no tiene un producto con stock suficiente y sin opciones obligatorias');
  return p;
}

describe.skipIf(!ready)('base real (solo locales demo)', () => {
  beforeAll(async () => {
    anon = createClient(URL!, ANON!, opts);
    service = createClient(URL!, SERVICE!, opts);
    const { data: d } = await service.from('tenants').select('id').eq('slug', DEMO_SLUG).single();
    const { data: p } = await service.from('tenants').select('id').eq('slug', PRO_DEMO_SLUG).single();
    demoTenantId = d!.id;
    proTenantId = p!.id;

    // Sign in as the demo owner with a magic link generated by the service key (no email sent)
    const { data: link, error } = await service.auth.admin.generateLink({ type: 'magiclink', email: PRO_DEMO_EMAIL });
    if (error) throw error;
    owner = createClient(URL!, ANON!, opts);
    const { error: vErr } = await owner.auth.verifyOtp({ token_hash: link.properties.hashed_token, type: 'magiclink' });
    if (vErr) throw vErr;
  }, 30_000);

  afterAll(async () => {
    for (const id of createdOrders) await service.rpc('cancel_order', { p_order_id: id, p_reason: 'prueba' });
    await owner?.auth.signOut();
  }, 30_000);

  describe('create_order', () => {
    it('cobra el precio de la base, no el que mande el navegador, y descuenta stock', async () => {
      const prod = await demoProduct(demoTenantId);
      const { data, error } = await anon.rpc('create_order', {
        p_tenant_slug: DEMO_SLUG, p_nickname: 'Prueba integración', p_payment_method: 'cash', p_order_type: 'aqui',
        p_items: [{ product_id: prod.id, quantity: 2, option_ids: [], price: 1 }],
      });
      expect(error).toBeNull();
      createdOrders.push((data as any).id);

      const { data: order } = await service.from('orders').select('total, status').eq('id', (data as any).id).single();
      expect(Number(order!.total)).toBe(Number(prod.price) * 2);
      expect(order!.status).toBe('Por Pagar');
      const { data: after } = await service.from('products').select('stock').eq('id', prod.id).single();
      expect(after!.stock).toBe(prod.stock - 2);
    });

    it('anular devuelve el stock', async () => {
      const prod = await demoProduct(demoTenantId);
      const { data } = await anon.rpc('create_order', {
        p_tenant_slug: DEMO_SLUG, p_nickname: 'Prueba anular', p_payment_method: 'cash', p_order_type: 'llevar',
        p_items: [{ product_id: prod.id, quantity: 3, option_ids: [] }],
      });
      const id = (data as any).id;
      const { data: ok } = await service.rpc('cancel_order', { p_order_id: id, p_reason: 'prueba' });
      expect(ok).toBe(true);
      const { data: after } = await service.from('products').select('stock').eq('id', prod.id).single();
      expect(after!.stock).toBe(prod.stock);
    });

    it('rechaza más de 10 unidades por línea y productos de otro local', async () => {
      const prod = await demoProduct(demoTenantId);
      const tooMany = await anon.rpc('create_order', {
        p_tenant_slug: DEMO_SLUG, p_nickname: 'Prueba', p_payment_method: 'cash', p_order_type: 'aqui',
        p_items: [{ product_id: prod.id, quantity: 11, option_ids: [] }],
      });
      expect(tooMany.error?.message).toMatch(/INVALID_QUANTITY/);

      const other = await demoProduct(proTenantId, 1);
      const foreign = await anon.rpc('create_order', {
        p_tenant_slug: DEMO_SLUG, p_nickname: 'Prueba', p_payment_method: 'cash', p_order_type: 'aqui',
        p_items: [{ product_id: other.id, quantity: 1, option_ids: [] }],
      });
      expect(foreign.error?.message).toMatch(/PRODUCT_NOT_FOUND/);
    });
  });

  describe('seguridad para un visitante sin sesión', () => {
    it('no ve pedidos, costos, errores ni invitaciones de un local real', async () => {
      const orders = await anon.from('orders').select('id').eq('tenant_id', proTenantId).limit(1);
      expect(orders.data ?? []).toHaveLength(0);
      for (const table of ['product_private', 'errores', 'tenant_invitations', 'tenant_members', 'cash_sessions']) {
        const r = await anon.from(table).select('*').limit(1);
        expect(r.data ?? [], table).toHaveLength(0);
      }
    });

    it('no puede llamar las funciones internas', async () => {
      for (const [fn, args] of [
        ['cancel_order', { p_order_id: proTenantId }],
        ['expire_unpaid_orders', {}],
        ['next_order_number', { p_tenant_id: proTenantId }],
      ] as const) {
        const r = await anon.rpc(fn, args as any);
        expect(r.error, fn).not.toBeNull();
      }
    });

    it('el costo ya no existe en la tabla pública de productos', async () => {
      const r = await anon.from('products').select('cost').limit(1);
      expect(r.error).not.toBeNull();
    });
  });

  describe('aislamiento entre locales (sesión del dueño demo Pro)', () => {
    it('solo ve su propio local', async () => {
      const { data } = await owner.from('tenants').select('id');
      expect((data ?? []).map(t => t.id)).toEqual([proTenantId]);
    });

    it('no puede modificar productos de otro local', async () => {
      const other = await demoProduct(demoTenantId, 1);
      const { data } = await owner.from('products').update({ price: 1 }).eq('id', other.id).select('id');
      expect(data ?? []).toHaveLength(0);
      const { data: still } = await service.from('products').select('price').eq('id', other.id).single();
      expect(Number(still!.price)).toBe(Number(other.price));
    });

    it('no puede subir fotos a la carpeta de otro local', async () => {
      const r = await owner.storage.from('images').upload(`${demoTenantId}/products/prueba-aislamiento.txt`, new Blob(['x']), { upsert: false });
      expect(r.error).not.toBeNull();
    });

    it('no ve la caja de otro local', async () => {
      const { data } = await owner.from('cash_sessions').select('id').eq('tenant_id', demoTenantId).limit(1);
      expect(data ?? []).toHaveLength(0);
    });
  });
});
